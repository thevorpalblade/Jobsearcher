"""Build jobsearcher/data/cities.tsv (which country a city is in) and countries.tsv
(each country's code and English name), for the search region (places.py). From
GeoNames via geonamescache, which is large (180 MB), so it's not a dependency:
pip install geonamescache, run this, commit the tables.

Each city row: name, country (ISO 3166 code), population, other names ("|"-separated).
Cities of 15,000 people or more in Europe, 100,000 or more elsewhere; other names
only in Latin script and capitalised (e.g. "München", "Göteborg"; "ROM" gives "Rom"),
as people type them, not transliterations.
"""

from __future__ import annotations

import re
from pathlib import Path

import geonamescache

DATA = Path(__file__).resolve().parent.parent / "jobsearcher" / "data"
OUT = DATA / "cities.tsv"
_LATIN = re.compile(r"^[A-Za-zÀ-ɏ' .\-]+$")


def main() -> None:
    gc = geonamescache.GeonamesCache(min_city_population=15000)
    europe = {iso for iso, c in gc.get_countries().items() if c["continentcode"] == "EU"}
    rows = []
    for city in gc.get_cities().values():
        country, population = city["countrycode"], int(city["population"])
        if population < (15000 if country in europe else 100000):
            continue
        name = city["name"]
        seen = {name.casefold()}
        others = []
        for alt in city.get("alternatenames") or []:
            alt = alt.strip()
            if len(alt) < 3 or len(alt) > 40 or not _LATIN.match(alt) or alt.islower():
                continue
            if alt.casefold() not in seen:
                seen.add(alt.casefold())
                others.append(alt)
        rows.append((name, country, population, "|".join(others)))
    rows.sort(key=lambda r: (-r[2], r[0]))
    with OUT.open("w", encoding="utf-8") as out:
        out.write("# Generated by scripts/build_places.py from GeoNames (CC BY 4.0).\n")
        for name, country, population, others in rows:
            out.write(f"{name}\t{country}\t{population}\t{others}\n")
    print(f"{len(rows)} cities -> {OUT}")
    countries = sorted((iso, c["name"]) for iso, c in gc.get_countries().items())
    with (DATA / "countries.tsv").open("w", encoding="utf-8") as out:
        out.write("# Generated by scripts/build_places.py from GeoNames (CC BY 4.0).\n")
        out.writelines(f"{iso}\t{name}\n" for iso, name in countries)
    print(f"{len(countries)} countries")


if __name__ == "__main__":
    main()
